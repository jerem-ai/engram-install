import type Database from 'better-sqlite3';
import { engramProfile } from './verbs.js';

/**
 * Render the agent-facing profile from reviewed sources only. The resulting
 * document is embedded in global snapshots and returned by context_bootstrap,
 * so legacy/unreviewed assertions must never be included here.
 */
export function renderEngramAgentProfile(
  db: Database.Database,
  generatedAt = new Date().toISOString(),
): string {
  const profile = engramProfile(db, { admission: 'promoted_only' });
  const lines: string[] = [];
  lines.push('---');
  lines.push('title: "Engram Agent Profile"');
  lines.push('type: agent_profile');
  lines.push(`generated_at: '${generatedAt}'`);
  lines.push('managed: true');
  lines.push('---');
  lines.push('');
  lines.push('# Engram Agent Profile');
  lines.push('');
  lines.push(`Generated: ${generatedAt}`);
  lines.push('');

  for (const [key, items] of Object.entries(profile.static)) {
    if (items.length > 0) {
      lines.push(`## ${key.charAt(0).toUpperCase() + key.slice(1)}`);
      lines.push('');
      for (const assertion of items) {
        lines.push(`- ${assertion.subject} ${assertion.predicate} ${assertion.object} (conf: ${assertion.confidence.toFixed(2)})`);
      }
      lines.push('');
    }
  }

  const dynamic = profile.dynamic;
  if (dynamic.activeProjects.length > 0) {
    lines.push('## Active Projects');
    lines.push('');
    for (const assertion of dynamic.activeProjects) {
      lines.push(`- ${assertion.subject} ${assertion.predicate} ${assertion.object}`);
    }
    lines.push('');
  }
  if (dynamic.openContradictions.length > 0) {
    lines.push('## Open Contradictions');
    lines.push('');
    for (const contradiction of dynamic.openContradictions) {
      lines.push(`- ${contradiction.subject} ${contradiction.predicate} (open)`);
    }
    lines.push('');
  }

  if (!Object.values(profile.static).some(assertions => assertions.length > 0)
    && dynamic.activeProjects.length === 0) {
    lines.push('No promoted assertions yet. Reviewed assertions populate after promotion and the next index cycle.');
    lines.push('');
  }

  lines.push('---');
  lines.push(`*Auto-generated by Engram profile generator on ${generatedAt}.*`);
  lines.push('');
  return lines.join('\n');
}
